"""Build every camera-ready appendix table from the raw result files (rebuttal experiments).

Writes LaTeX fragments to <out_dir> (default: paper_cr/MedProb_VLM_NeurIPS_2026/results/):
  cr_ct.tex               disease-labeled abdominal CT (Merlin) DS + 95% CI, 2D panel + MERLIN 3D
  cr_promptrobust.tex     prompt-wording robustness: per-modality summary + per-model L4/L5 x 4 styles
  cr_negation.tex         negation-realism (literature-grounded ladder): summary + per-modality tables
  cr_vqarad.tex           VQA-RAD closed yes/no downstream study
  cr_fairness.tex         skin tone (Fitzpatrick, L1-L3) and sex / age (L1-L5) subgroup DS
  cr_nstability.tex       DS vs. anchor-set size (n = 100 / 250 / 500 / 1000)
  cr_precision.tex        ROCO-CXR R@k alongside P@k
Also prints the headline counts quoted in the appendix prose.

Protocol everywhere: bootstrap B = 10,000, seed 42, percentile 95% CI; verdicts as in
_camera_ready_verdicts.py (collapse-certain: CI < 0; discriminating: CI > 0.05).
Env: lm_mi (numpy only; no matplotlib).  Run from repo root:
    python scripts/_camera_ready_appendix_tables.py [out_dir]
"""
import csv
import json
import sys
from pathlib import Path

import numpy as np

R = Path("experiments/results")
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "experiments/results/camera_ready_tables")
B, SEED, BOUND = 10_000, 42, 0.05

NAME = {"biomedclip": "BiomedCLIP", "pmc_clip": "PMC-CLIP", "pubmedclip": "PubMedCLIP",
        "openclip_vitb32": "OpenCLIP ViT-B/32", "openclip_vitl14": "OpenCLIP ViT-L/14",
        "siglip": "SigLIP", "medclip": "MedCLIP", "chexzero": "CheXzero", "biovil": "BioViL",
        "conch": "CONCH", "plip": "PLIP", "merlin": "MERLIN (3D)",
        # display names used inside the rebuttal CSVs
        "OpenCLIP ViT-B-32": "OpenCLIP ViT-B/32", "OpenCLIP ViT-L-14": "OpenCLIP ViT-L/14"}
ORDER = ["openclip_vitb32", "openclip_vitl14", "siglip", "biomedclip", "pmc_clip", "pubmedclip",
         "medclip", "chexzero", "biovil", "conch", "plip", "merlin"]
CSV_ORDER = ["OpenCLIP ViT-B-32", "OpenCLIP ViT-L-14", "SigLIP", "BiomedCLIP", "PMC-CLIP",
             "PubMedCLIP", "MedCLIP", "CheXzero", "BioViL", "CONCH", "PLIP", "MERLIN"]
MOD = {"cxr": "Chest X-ray", "brain_mri": "Brain MRI", "abdomen_ct_disease": "Abdominal CT",
       "fundus": "Retinal fundus", "dermoscopy": "Dermoscopy", "histopath": "Histopathology"}
MODS = list(MOD)


def boot(vals):
    v = np.asarray(vals, dtype=float)
    rng = np.random.default_rng(SEED)
    means = np.empty(B)
    for b in range(B):
        means[b] = v[rng.integers(0, len(v), len(v))].mean()
    return float(v.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def verdict(lo, hi):
    return "C" if hi < 0 else ("D" if lo > BOUND else "N")


def fmt(x, nd=3):
    s = f"{x:+.{nd}f}"
    return "-" + s[1:] if s.startswith("-") else s


def mark(x, v, nd=3):
    s = fmt(x, nd)
    if v == "D":
        return f"$\\mathbf{{{s}}}$"
    if v == "C":
        return f"\\collcell$^{{\\dagger}}{{{s}}}$"
    return f"${s}$"


def write(name, text):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("% Auto-generated by scripts/_camera_ready_appendix_tables.py -- do not edit.\n" + text,
                            encoding="utf-8")
    print("wrote", OUT / name)


# --------------------------------------------------------------------------- CT
def ct_table():
    V = json.load(open(R / "camera_ready_verdicts.json"))["abdomen_ct_disease"]
    rows = []
    for m in ORDER:
        if m not in V:
            continue
        cells = []
        for l in range(1, 6):
            c = V[m][f"L{l}"]
            cells.append(f"{mark(c['mean'], verdict(c['lo'], c['hi']))}\\,{{\\scriptsize[{fmt(c['lo'])},\\,{fmt(c['hi'])}]}}")
        rows.append(f"{NAME[m]} & " + " & ".join(cells) + " \\\\")
    cc = sum(verdict(V[m][L]["lo"], V[m][L]["hi"]) == "C" for m in V for L in V[m])
    print(f"[CT] collapse-certain cells: {cc}/{sum(len(V[m]) for m in V)}")
    write("cr_ct.tex", r"""\begin{table}[h]
  \centering\scriptsize
  \setlength{\tabcolsep}{2.5pt}
  \caption{Disease-labeled abdominal CT (Merlin, $n = 900$; 150 scans per finding):
  discrimination score with bootstrap $95\%$ CI. Markers as in Table~\ref{tab:medtec-cxr}.
  The 2D models see one windowed axial slice per scan; MERLIN sees the full volume.
  MedCLIP is a CXR specialist evaluated out of domain.}
  \label{tab:ct-merlin}
  \resizebox{\linewidth}{!}{%
  \begin{tabular}{l ccccc}
    \toprule
    Model & $L_{1}$ & $L_{2}$ & $L_{3}$ & $L_{4}$ & $L_{5}$ \\
    \midrule
""" + "\n".join("    " + r for r in rows) + r"""
    \bottomrule
  \end{tabular}}
\end{table}
""")


# ------------------------------------------------------------ prompt robustness
STY = ["template", "report", "ontology", "alt_clinical"]
STY_H = ["Template", "Report", "Ontology", "Alt.\\ clinical"]


def promptrobust():
    summary, per_mod, tot = [], [], dict(held=0, coll=0, cc=0, n=0)
    for mod in ["cxr", "fundus", "abdomen_ct_disease", "dermoscopy", "brain_mri", "histopath"]:
        rows = list(csv.DictReader(open(R / "promptrobust" / "tables" / f"table_promptrobust_{mod}_ci.csv")))
        mx = max(float(r[s]) for r in rows for s in STY)
        coll = [r for r in rows if float(r["template"]) < 0]
        held = [r for r in coll if all(float(r[s]) < BOUND for s in STY)]
        cc = sum(int(r[s + "_collapse_certain"]) for r in rows for s in STY)
        sd = np.median([float(r["sd_across_styles"]) for r in rows])
        tot["held"] += len(held); tot["coll"] += len(coll); tot["cc"] += cc; tot["n"] += 4 * len(rows)
        summary.append(f"{MOD[mod]} & {fmt(mx)} & {len(held)}/{len(coll)} & {cc}/{4 * len(rows)} & {sd:.3f} \\\\")
        body = []
        rows.sort(key=lambda r: (CSV_ORDER.index(r["model"]), r["level"]))
        for r in rows:
            cells = []
            for s in STY:
                v = "C" if int(r[s + "_collapse_certain"]) else ("D" if float(r[s + "_lo"]) > BOUND else "N")
                cells.append(mark(float(r[s]), v))
            body.append(f"{NAME.get(r['model'], r['model'])} & ${r['level'][0]}_{{{r['level'][1]}}}$ & " + " & ".join(cells) + " \\\\")
        per_mod.append((mod, body))
    print(f"[PR] held {tot['held']}/{tot['coll']}  collapse-certain {tot['cc']}/{tot['n']}")
    out = [r"""\begin{table}[h]
  \centering\small
  \caption{Prompt-wording robustness at $L_{4}$/$L_{5}$ (2D panel). ``Held'': template-collapsed
  cells (template $\mathrm{DS} < 0$) that stay below the $0.05$ boundary under all four wordings.
  ``Collapse-certain'': (model $\times$ level $\times$ style) cells with $95\%$ CI below $0$.
  Last column: median per-cell SD of DS across the four styles.}
  \label{tab:promptrobust-summary}
  \begin{tabular}{l c c c c}
    \toprule
    Modality & max DS (all cells $\times$ styles) & Held & Collapse-certain & median SD \\
    \midrule
""" + "\n".join("    " + s for s in summary) + f"""
    \\midrule
    All & & {tot['held']}/{tot['coll']} & {tot['cc']}/{tot['n']} & \\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""]
    for mod, body in per_mod:
        out.append(r"""\begin{table}[h]
  \centering\scriptsize
  \setlength{\tabcolsep}{4pt}
  \caption{Prompt robustness, """ + MOD[mod] + r""": DS under each wording style. Markers as in
  Table~\ref{tab:medtec-cxr}.}
  \begin{tabular}{l c cccc}
    \toprule
    Model & Level & """ + " & ".join(STY_H) + r""" \\
    \midrule
""" + "\n".join("    " + b for b in body) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")
    write("cr_promptrobust.tex", "\n".join(out))


# ----------------------------------------------------------------- negation
SUB = ["definite", "hedged", "ruled_out", "historical"]
SUB_H = ["Definite", "Hedged", "Ruled-out", "Historical$^{\\ddagger}$"]


def negation():
    LT = R / "lit_tables"
    summary, per_mod = [], []
    tot = dict(cc=0, n=0, hcc=0, hn=0, dcc=0, rcc=0)
    for mod in ["histopath", "cxr", "brain_mri", "fundus", "dermoscopy", "abdomen_ct_disease"]:
        rows = list(csv.DictReader(open(LT / f"table_negrealism_{mod}_A_ci.csv")))
        if mod == "abdomen_ct_disease":
            rows += [dict(r, model="MERLIN") for r in csv.DictReader(open(LT / "table_negrealism_abdomen_ct_disease_merlin_A_ci.csv"))]
        on = ["definite", "hedged", "ruled_out"]
        mx = max(float(r[s]) for r in rows for s in on)
        cc = sum(int(r[s + "_collapse_certain"]) for r in rows for s in on)
        hcc = sum(int(r["hedged_collapse_certain"]) for r in rows)
        tot["cc"] += cc; tot["n"] += 3 * len(rows); tot["hcc"] += hcc; tot["hn"] += len(rows)
        tot["dcc"] += sum(int(r["definite_collapse_certain"]) for r in rows)
