    roco = [("PMC-CLIP", 27.4, 66.4, 83.6), ("BiomedCLIP", 24.0, 58.2, 73.4), ("PubMedCLIP", 3.4, 9.0, 15.0),
            ("SigLIP", 3.4, 9.0, 14.1), ("OpenCLIP-L/14", 1.4, 6.5, 11.6), ("OpenCLIP-B/32", 0.8, 4.2, 5.9),
            ("BioViL", 2.5, 12.4, 18.4), ("CheXzero", 2.3, 9.6, 15.5), ("MedCLIP", 0.6, 3.1, 4.2)]
    body = [f"{m} & {a:.1f}\\% & {b:.1f}\\% & {c:.1f}\\% & {a:.1f}\\% & {b / 5:.1f}\\% & {c / 10:.1f}\\% \\\\"
            for m, a, b, c in roco]
