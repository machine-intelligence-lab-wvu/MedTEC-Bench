# -------------------------------------------------------------- N-stability
def nstability():
    d = json.load(open(R / "medtec_cxr_n1000.json"))
    body = []
    for m in ["biomedclip", "pmc_clip", "siglip"]:
        for L in ["L4", "L5"]:
            v = np.asarray([p["discrimination_score"] for p in d[m][L]["per_probe"]], dtype=float)
            perm = np.random.default_rng(SEED).permutation(len(v))
            ests, widths = [], {}
            for n in (100, 250, 500, 1000):
                mean, lo, hi = boot(v[perm[:n]])
                ests.append(fmt(mean, 4)); widths[n] = hi - lo
            body.append(f"{NAME[m]} & ${L[0]}_{{{L[1]}}}$ & " + " & ".join(ests) +
                        f" & {widths[100]:.4f} & {widths[1000]:.4f} \\\\")
    write("cr_nstability.tex", r"""\begin{table}[h]
  \centering\small
  \setlength{\tabcolsep}{4pt}
  \caption{Anchor-set size: chest-X-ray DS point estimate on nested random subsets
  (seed $42$) of the $n = 1{,}000$ anchors, and the bootstrap $95\%$ CI width at $n = 100$ and $n = 1{,}000$.}
  \label{tab:nstability}
  \begin{tabular}{l c cccc cc}
    \toprule
     & & \multicolumn{4}{c}{DS at $n =$} & \multicolumn{2}{c}{CI width} \\
    \cmidrule(lr){3-6} \cmidrule(lr){7-8}
    Model & Level & 100 & 250 & 500 & 1000 & $n{=}100$ & $n{=}1000$ \\
    \midrule
""" + "\n".join("    " + b for b in body) + r"""
    \bottomrule
  \end{tabular}
\end{table}
""")


