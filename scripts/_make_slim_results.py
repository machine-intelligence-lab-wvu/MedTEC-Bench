"""
Strip per-probe per-image arrays from MedTEC result JSONs, leaving only
the per-(model, level) summary fields. Useful for keeping the
submission package small; the full per_probe arrays are only needed to
re-compute bootstrap CIs and can be regenerated by re-running
scripts/run_medtec.py.

Run from repo root:
    python scripts/_make_slim_results.py
Outputs slim copies at experiments/results/slim/*.json.
"""
import json
from pathlib import Path

REPO = Path(__file__).parent.parent
SRC = REPO / "experiments" / "results"
DST = SRC / "slim"
DST.mkdir(exist_ok=True)

KEEP_FIELDS = {"avg_discrimination_score", "avg_collapse_ratio",
               "n_probes", "n_images", "ds"}


def slim_level(level_dict):
    if not isinstance(level_dict, dict):
        return level_dict
    return {k: v for k, v in level_dict.items() if k in KEEP_FIELDS}


def slim_model(model_dict):
    out = {}
    for k, v in model_dict.items():
        if isinstance(v, dict) and any(level_key in v for level_key in
                                       ("avg_discrimination_score", "ds",
                                        "per_probe")):
            out[k] = slim_level(v)
        else:
            out[k] = v
    return out


def main():
    targets = sorted(SRC.glob("medtec_*.json"))
    for src_path in targets:
        if "bootstrap" in src_path.name:
            continue  # already slim
        data = json.load(open(src_path, encoding="utf-8"))
        slim = {m: slim_model(r) for m, r in data.items()}
        out_path = DST / src_path.name
        json.dump(slim, open(out_path, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=2)
        old_kb = src_path.stat().st_size // 1024
        new_kb = out_path.stat().st_size // 1024
        print(f"  {src_path.name}: {old_kb:>7,} KB -> {new_kb:>5,} KB")


if __name__ == "__main__":
    main()
