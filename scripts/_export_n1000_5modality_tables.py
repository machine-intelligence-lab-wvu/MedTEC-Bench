"""
Aggregate n=1000 single-label MedTEC results across 5 disease-labeled modalities
and emit paradigm-grouped LaTeX tables.

Modalities: CXR (NIH n=1000), dermoscopy (ISIC), brain MRI (OASIS), histopathology
(NCT-CRC-HE), fundus (ODIR-5K).

Outputs (all under experiments/results/):
  tables_medtec_{cxr,derm,mri,histo,fundus}_n1000.tex   — per-modality paradigm-grouped
  tables_medtec_5modality_summary_n1000.tex             — unified summary across the
                                                           7 common multi-modality models
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
RR = REPO_ROOT / "experiments" / "results"

# Paradigm grouping (with display names)
PARADIGMS = [
    ("General-domain", [
        ("openclip_vitb32",   "OpenCLIP ViT-B/32"),
        ("openclip_vitl14",   "OpenCLIP ViT-L/14"),
        ("siglip",            "SigLIP"),
    ]),
    ("B: caption-pretrained", [
        ("biomedclip",  "BiomedCLIP"),
        ("pmc_clip",    "PMC-CLIP"),
        ("pubmedclip",  "PubMedCLIP"),
    ]),
    ("A: disease-retrieval", [
        ("medclip",     "MedCLIP"),
        ("chexzero",    "CheXzero"),
        ("biovil",      "BioViL"),
    ]),
    ("Pathology", [
        ("conch",       "CONCH"),
        ("plip",        "PLIP"),
    ]),
]

MODALITIES = [
    ("cxr",        "medtec_cxr_n1000.json",        "NIH-CXR (n=1{,}000 single-label, 5 classes)"),
    ("derm",       "medtec_dermoscopy_n1000.json", "ISIC dermoscopy (n=1{,}000, 5 classes)"),
    ("mri",        "medtec_brain_mri_n1000.json",  "OASIS brain MRI (n=1{,}000, 4 classes)"),
    ("histo",      "medtec_histopath_n1000.json",  "NCT-CRC-HE histopathology (n=999, 9 classes)"),
    ("fundus",     "medtec_fundus_n1000.json",     "ODIR-5K fundus (n=1{,}004, 7 classes)"),
]

LEVELS = ["L1", "L2", "L3", "L4", "L5"]
LEVEL_HEADERS = [
    ("$L_1$", "domain"),
    ("$L_2$", "modality"),
    ("$L_3$", "anatomy"),
    ("$L_4$", "finding"),
    ("$L_5$", "negation"),
]


def fmt_ds(v):
    """Format a DS value: blank for missing, bold negative for collapse."""
    if v is None:
        return "--"
    if isinstance(v, float) and v != v:
        return "NaN"
    sign = "+" if v >= 0 else ""
    cell = f"{sign}{v:.4f}"
    if v < 0:
        return f"\\textbf{{{cell}}}"
    return cell


def load_modality(json_path: Path) -> dict:
    """model_id -> {L1: ds, L2: ds, ...}"""
    raw = json.load(open(json_path))
    out = {}
    for m, r in raw.items():
        scores = {}
        for L in LEVELS:
            if L in r:
                v = r[L].get("avg_discrimination_score")
                if v is None:
                    v = r[L].get("ds")
                scores[L] = v
            else:
                scores[L] = None
        out[m] = scores
    return out


def per_modality_table(modality_key: str, modality_caption: str, scores: dict) -> str:
    lines = [
        "% Auto-generated by scripts/_export_n1000_5modality_tables.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        f"\\caption{{\\textbf{{\\textsc{{MedTEC-Bench}} discrimination scores on {modality_caption}.}} "
        "Higher is better; bold negative = collapse. "
        "Models grouped by training paradigm. Rows omitted when a model is out-of-domain "
        "for the modality (registry filter).}}",
        f"\\label{{tab:medtec-{modality_key}-n1000}}",
        "\\begin{tabular}{l l rrrrr}",
        "\\toprule",
        "Paradigm & Model & " + " & ".join(h[0] for h in LEVEL_HEADERS) + r" \\",
        " & & " + " & ".join(h[1] for h in LEVEL_HEADERS) + r" \\",
        "\\midrule",
    ]
    first_paradigm = True
    for paradigm, models in PARADIGMS:
        present = [(mid, mdisp) for (mid, mdisp) in models if mid in scores]
        if not present:
            continue
        if not first_paradigm:
            lines.append("\\midrule")
        first_paradigm = False
        for i, (mid, mdisp) in enumerate(present):
            paradigm_cell = paradigm if i == 0 else ""
            row = " & ".join([paradigm_cell, mdisp] + [fmt_ds(scores[mid][L]) for L in LEVELS])
            lines.append(row + r" \\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def cross_modality_summary(loaded: dict) -> str:
    """7 common multi-modality models × 5 modalities × 5 levels — show per-model
    mean DS across modalities (and std)."""
    common = ["biomedclip", "pmc_clip", "pubmedclip",
              "medclip",
              "openclip_vitb32", "openclip_vitl14", "siglip"]
    # Display & paradigm group
    display = {
        "biomedclip": ("B: caption-pretrained", "BiomedCLIP"),
        "pmc_clip":   ("B: caption-pretrained", "PMC-CLIP"),
        "pubmedclip": ("B: caption-pretrained", "PubMedCLIP"),
        "medclip":    ("A: disease-retrieval",  "MedCLIP"),
        "openclip_vitb32": ("General-domain", "OpenCLIP ViT-B/32"),
        "openclip_vitl14": ("General-domain", "OpenCLIP ViT-L/14"),
        "siglip":          ("General-domain", "SigLIP"),
    }
    # mean & std per (model, level) across 5 modalities
    import statistics
    per_model = {}
    for mid in common:
        per_model[mid] = {}
        for L in LEVELS:
            vals = []
            for mod_key, _, _ in MODALITIES:
                v = loaded[mod_key].get(mid, {}).get(L)
                if v is not None and not (isinstance(v, float) and v != v):
                    vals.append(v)
            if vals:
                per_model[mid][L] = (statistics.mean(vals),
                                     statistics.pstdev(vals) if len(vals) > 1 else 0.0,
                                     len(vals))
            else:
                per_model[mid][L] = None

    lines = [
        "% Auto-generated by scripts/_export_n1000_5modality_tables.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{\\textbf{Cross-modality \\textsc{MedTEC-Bench} summary at $n{=}1{,}000$.} "
        "Per-model mean discrimination score across the five disease-labeled modalities "
        "(NIH-CXR, ISIC, OASIS, NCT-CRC-HE, ODIR-5K), $\\pm$ population std. "
        "Bold negative = mean collapses. Every multi-modality model passes $L_1$--$L_3$ on average "
        "and collapses on $L_4$--$L_5$.}",
        "\\label{tab:medtec-5modality-summary-n1000}",
        "\\begin{tabular}{l l rrrrr}",
        "\\toprule",
        "Paradigm & Model & " + " & ".join(h[0] for h in LEVEL_HEADERS) + r" \\",
        " & & " + " & ".join(h[1] for h in LEVEL_HEADERS) + r" \\",
        "\\midrule",
    ]

    # group rows by paradigm
    paradigm_order = ["General-domain", "B: caption-pretrained", "A: disease-retrieval"]
    grouped = {p: [] for p in paradigm_order}
    for mid in common:
        p, disp = display[mid]
        grouped[p].append((mid, disp))

    first = True
    for p in paradigm_order:
        if not grouped[p]:
            continue
        if not first:
            lines.append("\\midrule")
        first = False
        for i, (mid, disp) in enumerate(grouped[p]):
            paradigm_cell = p if i == 0 else ""
            cells = []
            for L in LEVELS:
                mv = per_model[mid][L]
                if mv is None:
                    cells.append("--")
                else:
                    mean, std, n = mv
                    sign = "+" if mean >= 0 else ""
                    cell = f"{sign}{mean:.3f}"
                    if mean < 0:
                        cell = f"\\textbf{{{cell}}}"
                    cells.append(cell)
            lines.append(" & ".join([paradigm_cell, disp] + cells) + r" \\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def main():
    loaded = {}
    for key, fname, _ in MODALITIES:
        loaded[key] = load_modality(RR / fname)

    # Per-modality tables
    for key, fname, caption in MODALITIES:
        out = per_modality_table(key, caption, loaded[key])
        out_path = RR / f"tables_medtec_{key}_n1000.tex"
        out_path.write_text(out)
        print(f"wrote {out_path}")

    # Unified summary
    summary_tex = cross_modality_summary(loaded)
    out_path = RR / "tables_medtec_5modality_summary_n1000.tex"
    out_path.write_text(summary_tex)
    print(f"wrote {out_path}")

    # Console summary
    print("\n=== Cross-modality DS summary (mean ± std across 5 modalities) ===")
    print(f"{'Model':<22} {'L1':>14} {'L2':>14} {'L3':>14} {'L4':>14} {'L5':>14}")
    common = ["biomedclip", "pmc_clip", "pubmedclip", "medclip",
              "openclip_vitb32", "openclip_vitl14", "siglip"]
    import statistics
    for mid in common:
        row = [mid]
        for L in LEVELS:
            vals = [loaded[k].get(mid, {}).get(L) for k, _, _ in MODALITIES]
            vals = [v for v in vals if v is not None and not (isinstance(v, float) and v != v)]
            if not vals:
                row.append("--")
            else:
                m = statistics.mean(vals)
                s = statistics.pstdev(vals) if len(vals) > 1 else 0
                sign = "+" if m >= 0 else ""
                row.append(f"{sign}{m:.4f}±{s:.3f}")
        print(f"{row[0]:<22} " + " ".join(f"{c:>14}" for c in row[1:]))


if __name__ == "__main__":
    main()
