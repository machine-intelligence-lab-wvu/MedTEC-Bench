"""
Compute per-(model, modality, level) bootstrap CIs on the mean
discrimination score, using the n=1,000 single-label probe runs.

Inputs:
    experiments/results/medtec_cxr_n1000.json
    experiments/results/medtec_dermoscopy_n1000.json
    experiments/results/medtec_brain_mri_n1000.json
    experiments/results/medtec_histopath_n1000.json
    experiments/results/medtec_fundus_n1000.json

Outputs:
    experiments/results/medtec_bootstrap_ci_n1000.json
        {modality: {model: {level: {mean, ci_lo, ci_hi, n,
                                     ci_excludes_zero, collapse_certain}}}}
    experiments/results/table_medtec_ci_appendix_n1000.tex   (CXR table)
    experiments/results/table_medtec_ci_summary_n1000.tex    (per-modality
                                                               collapse counts)
"""
import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).parent.parent
RES = REPO / "experiments" / "results"

MODALITIES = [
    ("cxr",        "medtec_cxr_n1000.json",        "Chest X-ray"),
    ("brain_mri",  "medtec_brain_mri_n1000.json",  "Brain MRI"),
    ("fundus",     "medtec_fundus_n1000.json",     "Retinal fundus"),
    ("dermoscopy", "medtec_dermoscopy_n1000.json", "Dermoscopy"),
    ("histopath",  "medtec_histopath_n1000.json",  "Histopathology"),
]
LEVELS = ["L1", "L2", "L3", "L4", "L5"]
B = 10_000
SEED = 42

FAMILIES = [
    ("General-domain", [
        ("openclip_vitb32", "OpenCLIP-B/32"),
        ("openclip_vitl14", "OpenCLIP-L/14"),
        ("siglip",          "SigLIP"),
    ]),
    ("Broad biomedical", [
        ("biomedclip",  "BiomedCLIP"),
        ("pmc_clip",    "PMC-CLIP"),
        ("pubmedclip",  "PubMedCLIP"),
    ]),
    ("CXR specialist", [
        ("medclip",     "MedCLIP"),
        ("chexzero",    "CheXzero"),
        ("biovil",      "BioViL"),
    ]),
    ("Pathology", [
        ("conch",       "CONCH"),
        ("plip",        "PLIP"),
    ]),
]


def bootstrap_mean_ci(values, B=B, seed=SEED, alpha=0.05):
    arr = np.asarray(values, dtype=float)
    arr = arr[~np.isnan(arr)]
    if len(arr) < 2:
        return (float(arr.mean()) if len(arr) else float("nan"),
                float("nan"), float("nan"), int(len(arr)))
    rng = np.random.default_rng(seed)
    n = len(arr)
    idx = rng.integers(0, n, size=(B, n))
    sample_means = arr[idx].mean(axis=1)
    lo = float(np.percentile(sample_means, 100 * alpha / 2))
    hi = float(np.percentile(sample_means, 100 * (1 - alpha / 2)))
    return float(arr.mean()), lo, hi, int(n)


def main():
    out = {}
    for mod, fname, _ in MODALITIES:
        path = RES / fname
        if not path.exists():
            print(f"[skip] missing {path}")
            continue
        data = json.load(open(path, encoding="utf-8"))
        out[mod] = {}
        for mkey, mr in data.items():
            out[mod][mkey] = {}
            for lvl in LEVELS:
                if lvl not in mr:
                    continue
                probes = (mr[lvl] or {}).get("per_probe", [])
                vals = [pp["discrimination_score"] for pp in probes
                        if pp.get("discrimination_score") is not None]
                m, lo, hi, n = bootstrap_mean_ci(vals)
                out[mod][mkey][lvl] = {
                    "mean": m, "ci_lo": lo, "ci_hi": hi, "n": n,
                    "ci_excludes_zero": (not np.isnan(lo)) and (
                        (hi < 0) or (lo > 0)),
                    "collapse_certain": (not np.isnan(hi)) and (hi < 0),
                }

    out_path = RES / "medtec_bootstrap_ci_n1000.json"
    json.dump(out, open(out_path, "w", encoding="utf-8"), indent=2)
    print(f"wrote {out_path}")

    # ── CXR appendix table ─────────────────────────────────────────────
    cxr = out.get("cxr", {})
    lines = [
        "% Auto-generated by scripts/_compute_medtec_bootstrap_n1000.py",
        r"\begin{table}[t]\centering\footnotesize",
        r"\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.10}",
        r"\caption{\textsc{MedTEC-Bench} discrimination scores with "
        r"$95\%$ bootstrap CIs on the chest-radiograph probe set "
        r"($n{=}1{,}000$, $B{=}10{,}000$). Each cell: mean "
        r"$[\text{CI}_{2.5}, \text{CI}_{97.5}]$. \textbf{Bold} cells have "
        r"the $95\%$ CI strictly negative ($\mathrm{DS}<0$ at $p<0.05$).}",
        r"\label{tab:cxr-ci}",
        r"\begin{tabular}{l l ccccc}",
        r"\toprule",
        r"Family & Model & $L_{1}$ & $L_{2}$ & $L_{3}$ & $L_{4}$ & $L_{5}$ \\",
        r"\midrule",
    ]
    first_family = True
    for fam, models in FAMILIES:
        present = [(mid, mdisp) for mid, mdisp in models if mid in cxr]
        if not present:
            continue
        if not first_family:
            lines.append(r"\midrule")
        first_family = False
        for i, (mid, mdisp) in enumerate(present):
            row_cells = [f"\\multirow{{{len(present)}}}{{*}}{{\\textit{{{fam}}}}}" if i == 0 else "",
                         mdisp]
            for lvl in LEVELS:
                e = cxr[mid].get(lvl)
                if e is None:
                    row_cells.append("---")
                    continue
                cell = f"${e['mean']:+.3f}\\,[{e['ci_lo']:+.3f},{e['ci_hi']:+.3f}]$"
                if e["collapse_certain"]:
                    cell = f"\\textbf{{{cell}}}"
                row_cells.append(cell)
            lines.append(" & ".join(row_cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (RES / "table_medtec_ci_appendix_n1000.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RES / 'table_medtec_ci_appendix_n1000.tex'}")

    # ── Per-modality summary table ─────────────────────────────────────
    summary = []
    grand_cells = grand_collapses = 0
    for mod, _, label in MODALITIES:
        if mod not in out:
            continue
        n_models = len(out[mod])
        cells = sum(1 for m in out[mod] for l in out[mod][m])
        collapses = sum(1 for m in out[mod] for l in out[mod][m]
                        if out[mod][m][l]["collapse_certain"])
        rate = collapses / cells if cells else 0.0
        summary.append((label, n_models, cells, collapses, rate))
        grand_cells += cells
        grand_collapses += collapses

    sum_lines = [
        "% Auto-generated by scripts/_compute_medtec_bootstrap_n1000.py",
        r"\begin{table}[t]\centering\small",
        r"\setlength{\tabcolsep}{6pt}",
        r"\caption{Per-modality count of (model $\times$ level) cells with "
        r"$95\%$ bootstrap CI strictly excluding zero on the negative side "
        r"(\textsc{collapse} confirmed at $p<0.05$). $n=1{,}000$ "
        r"single-label probes per modality, $B=10{,}000$.}",
        r"\label{tab:ci-summary}",
        r"\begin{tabular}{l c c c c}",
        r"\toprule",
        r"Modality & Models & Total cells & Confirmed collapses & Rate \\",
        r"\midrule",
    ]
    for label, n_models, cells, collapses, rate in summary:
        sum_lines.append(
            f"{label} & {n_models} & {cells} & {collapses} & ${100*rate:.1f}\\%$ \\\\"
        )
    sum_lines.append(r"\midrule")
    grand_rate = grand_collapses / grand_cells if grand_cells else 0.0
    sum_lines.append(
        f"\\textit{{Total}} & --- & {grand_cells} & {grand_collapses} & ${100*grand_rate:.1f}\\%$ \\\\"
    )
    sum_lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (RES / "table_medtec_ci_summary_n1000.tex").write_text(
        "\n".join(sum_lines) + "\n", encoding="utf-8")
    print(f"wrote {RES / 'table_medtec_ci_summary_n1000.tex'}")

    # ── Console preview ────────────────────────────────────────────────
    print("\nCollapse-certain cells per modality (CI strictly < 0):")
    for label, n_models, cells, collapses, rate in summary:
        print(f"  {label:<18} {n_models} models, {collapses}/{cells} cells "
              f"collapse-certain ({100*rate:.1f}%)")
    print(f"  {'TOTAL':<18} ---        {grand_collapses}/{grand_cells} cells "
          f"collapse-certain ({100*grand_rate:.1f}%)")

    print("\nCXR per-cell point estimates with CIs:")
    print(f"  {'model':<22} " + " ".join(f"{L:>22}" for L in LEVELS))
    for fam, models in FAMILIES:
        for mid, mdisp in models:
            if mid not in cxr:
                continue
            row = [mdisp]
            for L in LEVELS:
                e = cxr[mid].get(L)
                if e is None:
                    row.append("---")
                else:
                    mark = "*" if e["collapse_certain"] else " "
                    row.append(f"{e['mean']:+.3f}{mark}[{e['ci_lo']:+.3f},{e['ci_hi']:+.3f}]")
            print(f"  {row[0]:<22} " + " ".join(f"{c:>22}" for c in row[1:]))


if __name__ == "__main__":
    main()
