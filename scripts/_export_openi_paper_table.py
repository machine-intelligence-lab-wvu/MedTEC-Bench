"""
Emit a paper-styled MedTEC discrimination-score table for the OpenI single-label
CXR probe set (n=3,295), matching the screenshot of "Table 2" in the draft.

Loads experiments/results/medtec_openi_cxr_full.json (already produced with the
4-positive L4/L5 prompt set used for the n=1,000 NIH-CXR run) and writes
experiments/results/tables_medtec_openi_n3295.tex.

Family grouping & row order match the screenshot exactly:
    General-domain     -> OpenCLIP ViT-B/32, OpenCLIP ViT-L/14, SigLIP
    Broad biomedical   -> BiomedCLIP, PMC-CLIP, PubMedCLIP
    CXR specialist     -> MedCLIP, CheXzero, BioViL

DS values: 4 decimals, bold negative.
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
RR = REPO_ROOT / "experiments" / "results"

JSON_PATH = RR / "medtec_openi_cxr_full.json"
OUT_PATH = RR / "tables_medtec_openi_n3295.tex"

FAMILIES = [
    ("General-domain", [
        ("openclip_vitb32",  "OpenCLIP ViT-B/32"),
        ("openclip_vitl14",  "OpenCLIP ViT-L/14"),
        ("siglip",           "SigLIP"),
    ]),
    ("Broad biomedical", [
        ("biomedclip",  "BiomedCLIP"),
        ("pmc_clip",    "PMC-CLIP"),
        ("pubmedclip",  "PubMedCLIP"),
    ]),
    ("CXR specialist", [
        ("medclip",     "MedCLIP"),
        ("chexzero",    "CheXzero"),
        ("biovil",      "BioViL"),
    ]),
]

LEVELS = ["L1", "L2", "L3", "L4", "L5"]
LEVEL_HEADERS = [
    ("$L_1$", "domain"),
    ("$L_2$", "modality"),
    ("$L_3$", "anatomy"),
    ("$L_4$", "finding"),
    ("$L_5$", "negation"),
]


def fmt_ds(v) -> str:
    if v is None:
        return "--"
    if isinstance(v, float) and v != v:
        return "NaN"
    sign = "+" if v >= 0 else ""
    cell = f"{sign}{v:.4f}"
    if v < 0:
        return f"\\textbf{{{cell}}}"
    return cell


def main() -> None:
    raw = json.load(open(JSON_PATH, encoding="utf-8"))

    def ds(model_id: str, level: str):
        m = raw.get(model_id) or {}
        lvl = m.get(level) or {}
        v = lvl.get("avg_discrimination_score")
        if v is None:
            v = lvl.get("ds")
        return v

    lines: list[str] = []
    lines.append("% Auto-generated by scripts/_export_openi_paper_table.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering\\small")
    lines.append("\\setlength{\\tabcolsep}{4pt}")
    lines.append(
        "\\caption{\\textsc{MedTEC-Bench} discrimination scores on the OpenI "
        "single-label chest-radiograph probe set "
        "($n{=}3{,}295$ anchor images: no\\_finding 2{,}221, "
        "pleural\\_effusion 491, consolidation 217, atelectasis 163, "
        "cardiomegaly 126, edema 77). Higher is better; $\\mathrm{DS}\\le 0$ "
        "indicates collapse. Models are grouped by training paradigm.}"
    )
    lines.append("\\label{tab:medtec-openi-n3295}")
    lines.append("\\begin{tabular}{l l rrrrr}")
    lines.append("\\toprule")
    lines.append("\\textbf{Family} & \\textbf{Model} & "
                 + " & ".join(h[0] for h in LEVEL_HEADERS) + r" \\")
    lines.append(" & & " + " & ".join(h[1] for h in LEVEL_HEADERS) + r" \\")
    lines.append("\\midrule")

    first_family = True
    for family, models in FAMILIES:
        present = [(mid, mdisp) for mid, mdisp in models if mid in raw]
        if not present:
            continue
        if not first_family:
            lines.append("\\midrule")
        first_family = False
        for i, (mid, mdisp) in enumerate(present):
            family_cell = f"\\textit{{{family}}}" if i == 0 else ""
            row_cells = [family_cell, mdisp] + [fmt_ds(ds(mid, L)) for L in LEVELS]
            lines.append(" & ".join(row_cells) + r" \\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    OUT_PATH.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH}")

    # Console preview
    print()
    print(f"{'Family':<20} {'Model':<22} " + " ".join(f"{L:>10}" for L in LEVELS))
    print("-" * 82)
    for family, models in FAMILIES:
        for i, (mid, mdisp) in enumerate(models):
            if mid not in raw:
                continue
            fam_print = family if i == 0 else ""
            cells = []
            for L in LEVELS:
                v = ds(mid, L)
                if v is None:
                    cells.append("    --   ")
                elif isinstance(v, float) and v != v:
                    cells.append("   NaN   ")
                else:
                    sign = "+" if v >= 0 else ""
                    cells.append(f"{sign}{v:.4f}")
            print(f"{fam_print:<20} {mdisp:<22} " + " ".join(f"{c:>10}" for c in cells))


if __name__ == "__main__":
    main()
